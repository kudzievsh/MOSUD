-- ============================================================
-- 7. Проверка созданной схемы через information_schema.
-- ============================================================
\echo ''
\echo '7A. Constraints in lab08 tables'
SELECT
    tc.table_name,
    tc.constraint_name,
    tc.constraint_type
FROM information_schema.table_constraints AS tc
WHERE tc.table_schema = 'lab'
  AND tc.table_name IN ('promotions', 'promotion_products', 'promotion_sellers')
ORDER BY tc.table_name, tc.constraint_type, tc.constraint_name;

\echo ''
\echo '7B. NOT NULL columns'
SELECT
    table_name,
    column_name
FROM information_schema.columns
WHERE table_schema = 'lab'
  AND table_name IN ('promotions', 'promotion_products', 'promotion_sellers')
  AND is_nullable = 'NO'
ORDER BY table_name, ordinal_position;

