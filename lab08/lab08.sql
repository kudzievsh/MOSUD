CREATE SCHEMA IF NOT EXISTS lab;

-- Безопасный повторный запуск: сначала удаляем зависимые таблицы.
DROP TABLE IF EXISTS lab.promotion_sellers;
DROP TABLE IF EXISTS lab.promotion_products;
DROP TABLE IF EXISTS lab.promotions;

-- ============================================================
-- 1. Сущность: promotions
--    Одна строка описывает одну промоакцию и период её действия.
-- ============================================================
CREATE TABLE lab.promotions (
    promotion_id bigint GENERATED BY DEFAULT AS IDENTITY,
    promo_code varchar(30) NOT NULL,
    promo_name varchar(120) NOT NULL,
    starts_on date NOT NULL,
    ends_on date NOT NULL,
    discount_pct numeric(5,2) NOT NULL,
    is_active boolean NOT NULL DEFAULT true,

    CONSTRAINT pk_promotions PRIMARY KEY (promotion_id),
    CONSTRAINT uq_promotions_promo_code UNIQUE (promo_code),
    CONSTRAINT ck_promotions_date_range CHECK (ends_on >= starts_on),
    CONSTRAINT ck_promotions_discount_pct CHECK (discount_pct > 0 AND discount_pct <= 90)
);

-- ============================================================
-- 2. Связующая таблица M:N: промоакция <-> товар Olist
--    Одна промоакция может включать много товаров; один товар может участвовать
--    во многих промоакциях.
-- ============================================================
CREATE TABLE lab.promotion_products (
    promotion_id bigint NOT NULL,
    product_id varchar(32) NOT NULL,
    max_units_per_order integer NOT NULL DEFAULT 1,

    CONSTRAINT pk_promotion_products PRIMARY KEY (promotion_id, product_id),
    CONSTRAINT fk_promotion_products_promotion
        FOREIGN KEY (promotion_id)
        REFERENCES lab.promotions(promotion_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,
    CONSTRAINT fk_promotion_products_product
        FOREIGN KEY (product_id)
        REFERENCES olist.products(product_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT ck_promotion_products_max_units
        CHECK (max_units_per_order > 0)
);

-- ============================================================
-- 3. Связующая таблица M:N: промоакция <-> продавец Olist
-- ============================================================
CREATE TABLE lab.promotion_sellers (
    promotion_id bigint NOT NULL,
    seller_id varchar(32) NOT NULL,
    seller_share_pct numeric(5,2) NOT NULL DEFAULT 50.00,

    CONSTRAINT pk_promotion_sellers PRIMARY KEY (promotion_id, seller_id),
    CONSTRAINT fk_promotion_sellers_promotion
        FOREIGN KEY (promotion_id)
        REFERENCES lab.promotions(promotion_id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,
    CONSTRAINT fk_promotion_sellers_seller
        FOREIGN KEY (seller_id)
        REFERENCES olist.sellers(seller_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT ck_promotion_sellers_share
        CHECK (seller_share_pct >= 0 AND seller_share_pct <= 100)
);

