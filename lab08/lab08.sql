-- Выбираем пять РЕАЛЬНЫХ product_id из Olist и связываем по одному с каждой промоакцией.
WITH chosen_products AS (
    SELECT product_id, row_number() OVER (ORDER BY product_id) AS rn
    FROM olist.products
    ORDER BY product_id
    LIMIT 5
),
chosen_promotions AS (
    SELECT promotion_id, row_number() OVER (ORDER BY promo_code) AS rn
    FROM lab.promotions
)
INSERT INTO lab.promotion_products
    (promotion_id, product_id, max_units_per_order)
SELECT
    cp.promotion_id,
    p.product_id,
    (p.rn + 1)::integer
FROM chosen_promotions AS cp
JOIN chosen_products AS p USING (rn);

-- Выбираем пять РЕАЛЬНЫХ seller_id из Olist и связываем по одному с каждой промоакцией.
WITH chosen_sellers AS (
    SELECT seller_id, row_number() OVER (ORDER BY seller_id) AS rn
    FROM olist.sellers
    ORDER BY seller_id
    LIMIT 5
),
chosen_promotions AS (
    SELECT promotion_id, row_number() OVER (ORDER BY promo_code) AS rn
    FROM lab.promotions
)
INSERT INTO lab.promotion_sellers
    (promotion_id, seller_id, seller_share_pct)
SELECT
    cp.promotion_id,
    s.seller_id,
    (40 + s.rn * 5)::numeric(5,2)
FROM chosen_promotions AS cp
JOIN chosen_sellers AS s USING (rn);

